"""Audit the complete meeting asset collection and create a local review gallery."""
import argparse
import hashlib
import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'output/meeting-generation'
parser = argparse.ArgumentParser()
parser.add_argument('--require-complete', action='store_true')
args = parser.parse_args()
specs = json.loads((OUT / 'prompts.json').read_text())['specs']
entries, missing = [], []
cards = []
for spec in specs:
    asset = ROOT / spec['asset']
    if not asset.exists():
        missing.append(spec['id'])
        continue
    entries.append({'id': spec['id'], 'asset': spec['asset'],
        'bytes': asset.stat().st_size,
        'sha256': hashlib.sha256(asset.read_bytes()).hexdigest()})
    identity = html.escape(spec['id'])
    name = html.escape(spec['name'] or spec['id'])
    role = html.escape(spec['role'] or ('Diện mạo hậu cung' if spec['female'] else 'Diện mạo triều thần'))
    background = 'harem-interior.webp' if spec['female'] else 'people-interior.webp'
    cards.append(f'''<article data-group="{'female' if spec['female'] else 'male'}">
      <a class="scene" href="../../{spec['asset']}" style="background-image:url('../../assets/images/{background}')">
      <img loading="lazy" src="../../{spec['asset']}" alt="{name}" width="1024" height="1536"></a>
      <h2>{name}</h2><p>{role} · {identity}</p></article>''')
assert len({e['sha256'] for e in entries}) == len(entries), 'Duplicate art files'
if args.require_complete:
    assert len(specs) == 90 and not missing, missing
manifest = {'method': 'built-in image_gen', 'identities': len(entries),
    'female': sum(s['female'] for s in specs if (ROOT/s['asset']).exists()),
    'male': sum(not s['female'] for s in specs if (ROOT/s['asset']).exists()),
    'missing': missing, 'bytes': sum(e['bytes'] for e in entries), 'assets': entries}
(OUT / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2))

if args.require_complete:
    registry = '// Generated by tools/package_meeting_gallery.py --require-complete.\n'
    registry += 'const meetingCharacterAssets = <String, String>{\n'
    registry += ''.join(f"  '{s['id']}': '{s['asset']}',\n" for s in specs)
    registry += '};\n'
    (ROOT / 'lib/game/presentation/meeting_assets.dart').write_text(registry)

page = '''<!doctype html><html lang="vi"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Vạn Tuế · Bộ ảnh toàn thân nhân vật</title><style>
*{box-sizing:border-box}body{margin:0;background:#f6efdf;color:#173e34;font:15px system-ui,sans-serif}header{padding:30px;position:sticky;top:0;z-index:2;background:#f6efdfed;backdrop-filter:blur(14px);border-bottom:1px solid #c5a971}h1{font:30px Georgia,serif;margin:0 0 10px}p{margin:6px 0}nav{display:flex;gap:10px;margin-top:16px}button{font:inherit;padding:8px 16px;border:1px solid #af9158;border-radius:20px;background:transparent;color:#173e34;cursor:pointer}button.active{background:#173e34;color:#fff4dc}main{padding:24px;display:grid;grid-template-columns:repeat(auto-fill,minmax(260px,1fr));gap:24px}article{background:#fff9ec;border:1px solid #d1bb8a;border-radius:14px;overflow:hidden}article[hidden]{display:none}.scene{display:block;height:460px;background-size:cover;background-position:center}.scene img{display:block;width:100%;height:100%;object-fit:contain;padding:12px}h2{font:20px Georgia,serif;margin:16px 16px 8px}article p{margin:0 16px 16px;font-size:12px}small{opacity:.8}
</style><header><h1>Vạn Tuế · Bộ ảnh toàn thân nhân vật</h1><p>90 diện mạo: 30 hậu cung · 60 triều thần. Giữ mẫu Ngọc Lan và Thanh Mai đã duyệt.</p><small>Bấm vào ảnh để mở tệp gốc trong game. Ảnh mỗi nhân vật được tạo riêng bằng imagegen.</small><nav><button class="active" data-filter="all">Tất cả</button><button data-filter="female">Hậu cung</button><button data-filter="male">Triều thần</button></nav></header><main>'''+''.join(cards)+'''</main><script>document.querySelectorAll('button').forEach(b=>b.onclick=()=>{document.querySelectorAll('button').forEach(x=>x.classList.toggle('active',x===b));document.querySelectorAll('article').forEach(x=>x.hidden=b.dataset.filter!=='all'&&x.dataset.group!==b.dataset.filter)})</script></html>'''
(OUT / 'review.html').write_text(page)
print(f"Meeting art: {len(entries)}/90; missing: {missing}; runtime bytes: {manifest['bytes']}")
